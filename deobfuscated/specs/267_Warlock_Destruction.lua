local TALENT_NODE_ID = 94840
local function isTalentNodeActive()
    if not (C_ClassTalents and (C_ClassTalents.GetActiveConfigID and (C_Traits and C_Traits.GetNodeInfo))) then
        return false
    end
    local ok, result = pcall(C_ClassTalents.GetActiveConfigID)
    if not (ok and type(result) == "number") then
        return false
    end
    local ok, result = pcall(C_Traits.GetNodeInfo, result, TALENT_NODE_ID)
    return ok and (result and (type(result.activeRank) == "number" and result.activeRank > 0))
end
